import type { Plugin, Rolldown } from "vite";
import type { Frontmatter, PageEntry } from "../src/lib/content/types.ts";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parse } from "yaml";
import { fileToPagePath, isContentFile } from "../src/lib/content/path.ts";

const CONTENT_DIR = "src/content";
const OUTPUT_FILE = "src/lib/content/content.gen.ts";

const PAGE_CSS_MODULE = "virtual:page-css";
const RESOLVED_PAGE_CSS_MODULE = `\0${PAGE_CSS_MODULE}`;

const BOM = /^\uFEFF/;

function readFrontmatter(file: string): Frontmatter {
  const lines = readFileSync(file, "utf8").replace(BOM, "").split(/\r?\n/);
  const end = lines.indexOf("---", 1);
  if (lines[0] !== "---" || end === -1)
    throw new Error(`Content page "${file}" has no frontmatter`);

  const frontmatter: Frontmatter = parse(lines.slice(1, end).join("\n"));
  if (!frontmatter.title) throw new Error(`Content page "${file}" has no title`);

  return frontmatter;
}

export function collectPages(root: string = CONTENT_DIR): PageEntry[] {
  const files = readdirSync(root, { recursive: true, encoding: "utf8" })
    .map((entry) => entry.replaceAll("\\", "/"))
    .filter(isContentFile);

  const takenBy = new Map<string, string>();

  const pages = files.map((file) => {
    const path = fileToPagePath(file);
    const taken = takenBy.get(path);
    if (taken) throw new Error(`Content collision: "${taken}" and "${file}" both map to "${path}"`);

    takenBy.set(path, file);
    return { path, ...readFrontmatter(join(root, file)) };
  });

  return pages.sort((a, b) => a.path.localeCompare(b.path));
}

function render(pages: PageEntry[]) {
  const paths = pages.map((page) => JSON.stringify(page.path)).join(", ");

  const entries = pages
    .map((page) => {
      const fields = Object.entries(page)
        .map(([key, value]) => `    ${key}: ${JSON.stringify(value)},\n`)
        .join("");

      return `  {\n${fields}  },\n`;
    })
    .join("");

  return `/* oxlint-disable */
// AUTOGENERATED by vite/content.ts — do not edit

import type { PageEntry } from "./types";

export const PAGE_PATHS = [${paths}] as const;

export type PagePath = (typeof PAGE_PATHS)[number];

export const PAGES: PageEntry[] = ${entries ? `[\n${entries}]` : "[]"};
`;
}

function generate(root: string = CONTENT_DIR, outputFile: string = OUTPUT_FILE) {
  const output = render(collectPages(root));
  if (existsSync(outputFile) && readFileSync(outputFile, "utf8") === output) return;
  writeFileSync(outputFile, output);
}

function isContentChange(path: string, root: string = CONTENT_DIR) {
  return !relative(root, path).replaceAll("\\", "/").startsWith("..");
}

function collectChunkCss(
  bundle: Rolldown.OutputBundle,
  fileName: string,
  seen: Set<string>,
): string[] {
  const chunk = bundle[fileName];
  if (seen.has(fileName) || chunk?.type !== "chunk" || chunk.isEntry) return [];
  seen.add(fileName);

  return [
    ...chunk.imports.flatMap((imported) => collectChunkCss(bundle, imported, seen)),
    ...(chunk.viteMetadata?.importedCss ?? []),
  ];
}

function collectPageCss(bundle: Rolldown.OutputBundle, contentRoot: string, base: string) {
  const pageCss: Record<string, string[]> = {};

  for (const chunk of Object.values(bundle)) {
    if (chunk.type !== "chunk" || !chunk.facadeModuleId) continue;

    const file = relative(contentRoot, chunk.facadeModuleId).replaceAll("\\", "/");
    if (file.startsWith("..") || !isContentFile(file)) continue;

    const css = new Set(collectChunkCss(bundle, chunk.fileName, new Set()));
    if (css.size) pageCss[fileToPagePath(file)] = [...css].map((href) => base + href);
  }

  return pageCss;
}

export function content(): Plugin {
  let contentRoot = CONTENT_DIR;
  let base = "/";
  let pageCss: Record<string, string[]> = {};

  return {
    name: "content",
    configResolved(config) {
      contentRoot = join(config.root, CONTENT_DIR);
      base = config.base;
    },
    buildStart() {
      generate();
    },
    resolveId(id) {
      return id === PAGE_CSS_MODULE ? RESOLVED_PAGE_CSS_MODULE : null;
    },
    load(id) {
      if (id !== RESOLVED_PAGE_CSS_MODULE) return null;
      const css = this.environment.name === "ssr" ? pageCss : {};
      return `export default ${JSON.stringify(css)};`;
    },
    generateBundle(_options, bundle) {
      if (this.environment.name === "client") pageCss = collectPageCss(bundle, contentRoot, base);
    },
    configureServer(server) {
      for (const event of ["add", "change", "unlink", "unlinkDir"] as const) {
        server.watcher.on(event, (path) => {
          if (isContentChange(path)) generate();
        });
      }
    },
  };
}
