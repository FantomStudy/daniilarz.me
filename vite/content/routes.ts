import type { ContentFile } from "./collect.ts";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { collectContentFiles } from "./collect.ts";

export const ROUTES_DIR = "src/routes/(content)";

const UNESCAPABLE = /[$%!#?:*<>|()[\]{}]/;

// Экранируем то, что роутер прочитает как свой синтаксис: точки, route.tsx, префикс "-" и суффикс "_"
function escapeSegment(segment: string, file: string) {
  if (UNESCAPABLE.test(segment))
    throw new Error(`Content page "${file}" has characters the router can't use in a path`);
  if (segment === "route") return "[route]";
  return segment.replaceAll(".", "[.]").replace(/^-/, "[-]").replace(/_$/, "[_]");
}

function routeFile(file: string) {
  const segments = file.slice(0, file.lastIndexOf(".")).split("/");
  return segments.map((segment) => escapeSegment(segment, file)).join("/") + ".tsx";
}

// "/bar" -> "/(content)/bar", "/blog" -> "/(content)/blog/", "/" -> "/(content)/"
function routeId(file: string, path: string) {
  const isIndex = file.slice(0, file.lastIndexOf(".")).split("/").at(-1) === "index";
  return `/(content)${path === "/" ? "" : path}${isIndex ? "/" : ""}`;
}

const HEADER = "// AUTOGENERATED by vite/content/routes.ts";

function render({ file, page }: ContentFile) {
  const fields = Object.entries(page)
    .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},\n`)
    .join("");

  return `/* oxlint-disable */
${HEADER} from src/content/${file} — do not edit

import type { PageEntry } from "@/lib/content/types";
import { createFileRoute } from "@tanstack/react-router";
import Content from "@/content/${file}";
import { pageHead } from "@/lib/content/head";

const page: PageEntry = {
${fields}};

export const Route = createFileRoute(${JSON.stringify(routeId(file, page.path))})({
  staticData: { page },
  head: () => pageHead(page),
  component: Content,
});
`;
}

function write(file: string, output: string) {
  if (existsSync(file) && readFileSync(file, "utf8") === output) return;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, output);
}

export function writeRoute(contentFile: ContentFile, routesDir: string = ROUTES_DIR) {
  write(join(routesDir, routeFile(contentFile.file)), render(contentFile));
}

export function syncRoutes(routesDir: string = ROUTES_DIR) {
  const contentFiles = collectContentFiles();
  const expected = new Set(contentFiles.map(({ file }) => routeFile(file)));

  if (existsSync(routesDir)) {
    for (const entry of readdirSync(routesDir, { recursive: true, encoding: "utf8" })) {
      const file = entry.replaceAll("\\", "/");
      if (!file.endsWith(".tsx") || expected.has(file)) continue;
      // Рукописные файлы вроде route.tsx живут рядом со сгенерированными — удаляем только свои
      const path = join(routesDir, file);
      if (readFileSync(path, "utf8").includes(HEADER)) rmSync(path);
    }
  }

  for (const contentFile of contentFiles) writeRoute(contentFile, routesDir);
}
